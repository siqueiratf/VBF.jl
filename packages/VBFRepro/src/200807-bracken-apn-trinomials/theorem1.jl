# Implements Theorem 1 — APN property of Family 1.
# Paper: Bracken, Byrne, Markin, McGuire (2008),
#        "New Families of Quadratic Almost Perfect Nonlinear Trinomials and Multinomials",
#        Finite Fields and Their Applications 14 (2008), 703–714
# Section: 2 — Proof of APN property for family (1)
#
# Pseudocode:
#   For each (k, s) with k,s odd and gcd(k,s)=1:
#     1. b ← primitive element ω of GF(2^{2k})  [not a cube since ord(ω)=2^{2k}−1]
#     2. c ← ω^2  [not in GF(2^k) since ord(ω^2)=2^{2k}−1, which does not divide 2^k−1]
#     3. r_i ← ω^{e_i} ∈ GF(2^k) (or 0 for the pure trinomial)
#     4. F ← family1_lut(k, s, b, c, r)
#     5. assert differential_uniformity(SBox(F)) == 2
# VBF API used: SBox, differential_uniformity, gf_pow, gf_is_dth_power, in_subfield,
#               subfield_elements

include(joinpath(@__DIR__, "helpers.jl"))

using Random


# Smallest valid (k,s) pairs: both odd, gcd(k,s)=1.
# k=3 (n=6) is the smallest k≥1 that yields a non-degenerate polynomial over GF(2^{2k})
# (k=1 gives degenerate exponents mod 2^2−1=3).
#
# The r-coefficients are given as ω-exponents (ω = 2, the primitive element the
# modulus encodes), never as indices into `subfield_elements`: that list is sorted by
# integer value, so index 1 is always the element 1 and never a power of ω.
# GF(2^k)* ⊂ GF(2^{2k})* is the subgroup generated by ω^{2^k+1}, so the admissible
# exponents for k=3 are the multiples of (2^6−1)/(2^3−1) = 9.

const THEOREM1_CASES = [
    # (k, s, label, r_exp) — r_exp[i] is the ω-exponent of r_i, `nothing` ⇒ r_i = 0
    # --- n=6, k=3, s=1 ---
    (3, 1, "n=6  k=3 s=1  trinomial    (r=[0, 0])",              [nothing, nothing]),
    (3, 1, "n=6  k=3 s=1  quadrinomial (r=[ω⁹=24, 0])",          [9, nothing]),
    (3, 1, "n=6  k=3 s=1  pentanomial  (r=[ω⁹=24, ω¹⁸=15])",     [9, 18]),
    # --- n=6, k=3, s=5 (also odd, gcd(3,5)=1) ---
    (3, 5, "n=6  k=3 s=5  trinomial",                            [nothing, nothing]),
    # --- n=10, k=5, s=1 (bounded demo) ---
    (5, 1, "n=10 k=5 s=1  trinomial",           [nothing, nothing, nothing, nothing]),
]


"""
    theorem1_sbox(k, s, r_exp; modulus) -> SBox

Build a Family 1 SBox with b=2 (=ω, primitive hence not a cube), c=ω² (not in
GF(2^k)), and `r[i] = ω^{r_exp[i]}`, where `r_exp[i] === nothing` means `r_i = 0`.
The Theorem 1 hypotheses — including `r_i ∈ GF(2^k)` — are enforced by
`family1_lut`.
"""
function theorem1_sbox(k::Int, s::Int, r_exp::AbstractVector;
                        modulus::Int = primitive_polynomial(2k))
    n     = 2k
    r     = Int[e === nothing ? 0 : gf_pow(2, e, n; modulus) for e in r_exp]
    b, c  = 2, gf_pow(2, 2, n; modulus)   # b=ω, c=ω^2
    SBox(family1_lut(k, s, b, c, r; modulus))
end


"""
    theorem1_valid_parameters_n6(; modulus) -> (bs, cs, rs)

The full Theorem 1 parameter space at n=6, (k,s)=(3,1): `bs` = the 42 non-cubes
of GF(64)*, `cs` = the 56 elements outside GF(8), `rs` = the 8 elements of GF(8)
(from which r₁ and r₂ are drawn independently). |bs|·|cs|·|rs|² = 150 528.
"""
function theorem1_valid_parameters_n6(; modulus::Int = primitive_polynomial(6))
    n, k = 6, 3
    bs = [b for b = 1:(1 << n) - 1 if !gf_is_dth_power(b, 3, n; modulus)]
    cs = [c for c = 0:(1 << n) - 1 if !in_subfield(c, k, n; modulus)]
    rs = subfield_elements(n, k; modulus)
    (bs, cs, rs)
end


"""
    theorem1_sweep_n6(; full_search=false, sample=400, seed=20080701)
        -> (tested, total, all_apn)

Sweep the Theorem 1 parameter space at n=6, (k,s)=(3,1). `total` is always the
size of the full space (150 528 tuples). With `full_search=true` every tuple is
built and its differential uniformity checked (≈7 s); otherwise a reproducible
random sample of `sample` tuples is checked, and `tested` reports the fraction
that was actually covered.
"""
function theorem1_sweep_n6(; full_search::Bool = false, sample::Int = 400,
                            seed::Int = 20_080_701)
    k, s, n = 3, 1, 6
    modulus = primitive_polynomial(n)
    bs, cs, rs = theorem1_valid_parameters_n6(; modulus)
    total = length(bs) * length(cs) * length(rs)^2

    tuples = if full_search
        [(b, c, r1, r2) for b in bs for c in cs for r1 in rs for r2 in rs]
    else
        rng = MersenneTwister(seed)
        [(rand(rng, bs), rand(rng, cs), rand(rng, rs), rand(rng, rs)) for _ = 1:sample]
    end

    all_apn = true
    for (b, c, r1, r2) in tuples
        F = SBox(family1_lut(k, s, b, c, [r1, r2]; modulus))
        if differential_uniformity(F) != 2
            all_apn = false
            break
        end
    end
    (length(tuples), total, all_apn)
end


# Parameter tuples that each violate exactly one Theorem 1 hypothesis. Building
# them requires `validate=false`; every one of them fails to be APN, which is
# what makes the hypotheses necessary rather than merely sufficient.
const THEOREM1_VIOLATIONS = [
    # (b, c, r, why)
    (1,  4, [0, 0], "b=1=ω⁰ is a cube"),
    (3,  4, [0, 0], "b=3 is a cube"),
    (8,  4, [0, 0], "b=8=ω³ is a cube"),
    (13, 4, [0, 0], "b=13 is a cube"),
    (2,  0, [0, 0], "c=0 ∈ GF(8)"),
    (2,  1, [0, 0], "c=1 ∈ GF(8)"),
    (2, 14, [0, 0], "c=14 ∈ GF(8)"),
    (2, 15, [0, 0], "c=15 ∈ GF(8)"),
    (2,  4, [2, 0], "r₁=2 ∉ GF(8)"),
    (2,  4, [0, 3], "r₂=3 ∉ GF(8)"),
]


"""
    theorem1_necessity_report(io)

Show that the Theorem 1 hypotheses are *necessary*: each tuple in
`THEOREM1_VIOLATIONS` breaks exactly one of them and the resulting function has
differential uniformity > 2. The builder refuses these tuples by default, so
they are constructed with `validate=false` — the only legitimate use of that
keyword.
"""
function theorem1_necessity_report(io::IO = stdout)
    k, s, n = 3, 1, 6
    modulus = primitive_polynomial(n)
    println(io, "  Hypotheses are necessary (n=6, k=3, s=1) — each tuple below breaks")
    println(io, "  exactly one hypothesis, is rejected by family1_lut, and is not APN:")
    all_rejected = true
    for (b, c, r, why) in THEOREM1_VIOLATIONS
        rejected = false
        try
            family1_lut(k, s, b, c, r; modulus)
        catch e
            rejected = e isa ArgumentError
        end
        du = differential_uniformity(
            SBox(family1_lut(k, s, b, c, r; modulus, validate = false)))
        ok = rejected && du != 2
        all_rejected &= ok
        print_check("$why → rejected by family1_lut, du = $du ≠ 2", ok, io)
    end
    println(io)
    print_check("All Theorem 1 hypothesis violations rejected and non-APN",
                all_rejected, io)
    println(io)
end


function theorem1_report(io::IO = stdout; full_search::Bool = false)
    print_section("Theorem 1 — Family 1 quadratic APN multinomials (Section 2)", io)
    println(io, "  F(x) = b·x^{2^s+1} + b^{2^k}·x^{2^{k+s}+2^k} + c·x^{2^k+1}")
    println(io, "         + Σ_{i=1}^{k−1} r_i·x^{2^{i+k}+2^i}")
    println(io, "  Conditions: k,s odd, gcd(k,s)=1, b not a cube, c ∉ GF(2^k), r_i ∈ GF(2^k).")
    println(io)

    all_pass = true
    for (k, s, label, r_exp) in THEOREM1_CASES
        modulus = primitive_polynomial(2k)
        F   = theorem1_sbox(k, s, r_exp; modulus)
        apn = differential_uniformity(F) == 2
        all_pass &= apn
        print_check(label, apn, io)
    end
    println(io)
    print_check("All Theorem 1 instances APN", all_pass, io)
    print_kv("b", "2 = ω (primitive ⇒ not a cube)", io)
    print_kv("c", "4 = ω² (not in GF(2^k))", io)
    println(io)

    theorem1_necessity_report(io)

    tested, total, sweep_apn = theorem1_sweep_n6(; full_search)
    print_check("n=6 (k,s)=(3,1) sweep: $tested/$total valid (b,c,r₁,r₂) tuples APN",
                sweep_apn, io)
    pct = round(100 * tested / total; digits = 2)
    print_kv("completeness",
             full_search ?
             "n=6 (k,s)=(3,1): all $total valid (b,c,r₁,r₂) tuples (100%); " *
             "(k,s)=(3,5) and n=10 single instances" :
             "n=6 (k,s)=(3,1): $tested of $total valid (b,c,r₁,r₂) tuples ($pct%, " *
             "seeded random sample — pass full_search=true for all $total); " *
             "(k,s)=(3,5) and n=10 single instances", io)
end


if abspath(PROGRAM_FILE) == @__FILE__
    theorem1_report(; full_search = "--full" in ARGS)
end
