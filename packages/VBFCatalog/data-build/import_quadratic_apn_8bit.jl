const N = 8
const MOD8 = conway_polynomial(N)

# --- EP09: SAGE polynomials in eightBitAPN.all_quadratic_polynomials() ---------

# Balanced extraction of every `poly_to_lut(<expr>)` argument in a function body.
function _poly_to_lut_args(body::AbstractString)
    out = String[]; i = firstindex(body)
    while (j = findnext("poly_to_lut(", body, i)) !== nothing
        k = nextind(body, last(j)); depth = 1; start = k
        while depth > 0
            c = body[k]; c == '(' && (depth += 1); c == ')' && (depth -= 1)
            k = nextind(body, k)
        end
        push!(out, strip(body[start:prevind(body, prevind(body, k))]))
        i = k
    end
    out
end

# Expand `sum(X**(K*2**i) for i in range(0, N))` to `(X**K + X**2K + … + X**128K)`,
# normalise the `**` powers + a stray `+  +` typo to VBF polynomial syntax.
function _normalise_sage_poly(e::AbstractString)
    while (m = match(r"sum\(X\*\*\((\d+)\*2\*\*i\) for i in range\(0, ?N\)\)", e)) !== nothing
        K = parse(Int, m.captures[1])
        e = replace(e, m.match => "(" * join(["X**$(K * (1 << i))" for i in 0:N - 1], " + ") * ")")
    end
    replace(replace(e, r"\+\s*\+" => "+"), r"\s+" => " ")
end

function _edelpott_luts(apndb::AbstractString)
    src = read(joinpath(apndb, "eightBitAPN.py"), String)
    i0 = findfirst("def all_quadratic_polynomials", src)
    i1 = findnext("\ndef ", src, last(i0) + 1)
    body = src[last(i0):(i1 === nothing ? lastindex(src) : first(i1))]
    [polynomial_to_lut(_normalise_sage_poly(e), N, MOD8) for e in _poly_to_lut_args(body)]
end

# --- WTG13: raw LUTs in eightBitAPN.all_WenTanGon() (the only raw lists there) -
_wengtangong_luts(apndb) =
    [l for l in parse_apn_lut_file(joinpath(apndb, "eightBitAPN.py")) if length(l) == 256]

# --- Taniguchi: the two new (a≠0) classes generated from Theorem 3 ------------
_taniguchi_luts(_) = [Int.(r.sbox.lut) for r in taniguchi_apn_representatives(4) if r.new]

# --- one family -> a bulk corpus ---------------------------------------------

struct Family
    name::String          # corpus name / side-store stem
    bib_key::String
    loader::Function      # apndb -> Vector{Vector{Int}}
    notes::String
end

const FAMILIES = Family[
    Family("edelpott2009_n8", "EdelPott2009",
        apndb -> _edelpott_luts(apndb),
        "Edel–Pott 2009: the 22 quadratic 8-bit APN functions (Table 9), from SAGE polynomials."),
    Family("wengtangong2013_n8", "WengTanGong2013",
        apndb -> _wengtangong_luts(apndb),
        "Weng–Tan–Gong 2013: the 10 new quadratic 8-bit APN functions (APN-algebra search)."),
    Family("yuwangli2014_qam_n8", "YuWangLi2014QAM",
        apndb -> parse_apn_lut_file(joinpath(apndb, "firstQAM.py")),
        "Yu–Wang–Li 2014: quadratic 8-bit APN found by the QAM method (firstQAM)."),
    Family("taniguchi2019_n8", "Taniguchi2019",
        _taniguchi_luts,
        "Taniguchi 2019: the two new CCZ-classes (Theorem 3, a≠0), generated by taniguchi_apn."),
    Family("beierleleander2022_n8", "BeierleLeander2022",
        apndb -> parse_apn_lut_file(joinpath(apndb, "BeierleLeander.py")),
        "Beierle–Leander 2022: quadratic 8-bit APN from the recursive tree search."),
    Family("yuperrin2022_qam_n8", "YuPerrin2022QAM",
        apndb -> parse_apn_lut_file(joinpath(apndb, "secondQAM.py")),
        "Yu–Perrin 2022: more quadratic 8-bit APN by the QAM method (secondQAM)."),
    Family("beierleleanderperrin2022_n8", "BeierleLeanderPerrin2022Trims",
        apndb -> parse_apn_lut_file(joinpath(apndb, "apn_8bit_BLP22.py")),
        "Beierle–Leander–Perrin 2022: quadratic 8-bit APN from trims/extensions."),
]

function import_family!(db::SQLite.DB, fam::Family, apndb::AbstractString;
                        powtab, source_repo, contributor, added)
    luts = fam.loader(apndb)
    encodings = Vector{UInt8}[]; skipped = 0
    for lut in luts
        length(lut) == 1 << N || error("$(fam.name): member is not a 2^$N LUT")
        F = SBox{N}(lut)
        if differential_uniformity(F) == 2 && algebraic_degree(F) == 2
            push!(encodings, encode_quadratic(F; modulus = MOD8, powtab = powtab))
        else
            skipped += 1   # APN but not quadratic (e.g. firstQAM's single degree-4 member)
        end
    end
    isempty(encodings) && error("$(fam.name): no quadratic-APN members loaded")
    notes = fam.notes * (skipped > 0 ?
        " ($(skipped) non-quadratic-APN member(s) in the source excluded)" : "")
    store = build_corpus_store!(fam.name, encodings)
    register_corpus!(db;
        name = fam.name, n = N, m = N, member_count = store.count, degree = 2,
        modulus = MOD8, encoding = "quadratic-coeffs-v1",
        bytes_per_member = store.bytes_per_member,
        store_file = "corpora/" * fam.name * ".sqlite", store_sha256 = store.sha256,
        family = "quadratic-apn-8bit", bib_key = fam.bib_key,
        source_repo = source_repo, contributor = contributor, added_date = added,
        notes = notes)
    println("[$(fam.name)] members=$(store.count) skipped=$(skipped) " *
            "bytes/member=$(store.bytes_per_member) bib=$(fam.bib_key)")
    store.count
end

function main()
    apndb = joinpath(sboxu_path(), "sboxU", "scripts", "apnDB")
    isdir(apndb) || error("apnDB not found at $apndb")
    sha = sboxu_short_sha(sboxu_path())
    bfa_sha = try readchomp(`git -C $(pkgdir(VBF)) rev-parse --short HEAD`) catch; "unknown" end
    source_repo = "bfa@$bfa_sha|sboxu@$sha"
    contributor = "BFA quadratic-APN 8-bit literature import (automated)"
    added = string(Dates.now(Dates.UTC)) * "Z"
    @info "quadratic-APN 8-bit re-housing" apndb sha bfa_sha
    powtab = monomial_power_table(N, MOD8)
    db = load_catalog()
    try
        total = 0
        for fam in FAMILIES
            total += import_family!(db, fam, apndb;
                powtab = powtab, source_repo = source_repo,
                contributor = contributor, added = added)
        end
        println("[quadratic-apn-8bit] TOTAL members re-housed = $total across $(length(FAMILIES)) corpora")
    finally
        close(db)
    end
    return nothing
end

if !isinteractive() && get(ENV, "BFA_QAPN8_NO_AUTORUN", "0") != "1"
    main()
end
