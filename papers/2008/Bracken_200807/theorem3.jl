# Implements Theorem 3 — APN property of Family 2, plus Lemma 2 checks.
# Paper: Bracken, Byrne, Markin, McGuire (2008),
#        "New Families of Quadratic Almost Perfect Nonlinear Trinomials and Multinomials",
#        Finite Fields and Their Applications 14 (2008), 703–714
# Section: 3 — Proof of APN property for family (2)
#
# Pseudocode (Theorem 3):
#   For each (k, s) with gcd(s,3k)=1, k≢0 mod 3, k+s≡0 mod 3:
#     1. u ← primitive element of GF(2^{3k})
#     2. For v=0 (binomial) and v=ω^{(2^{3k}−1)/(2^k−1)} ∈ GF(2^k)* (trinomial):
#        F ← family2_lut(k, s, u, v)
#        assert differential_uniformity(SBox(F)) == 2
#
# Pseudocode (Lemma 2):
#   For GF(2^{3k}), k not divisible by 3:
#     (i)  every θ ∈ GF(2^k) is a 7th power *of an element of GF(2^k)*
#          [7∤(2^k−1) since 3∤k, so x ↦ x^7 permutes GF(2^k)]
#     (ii) u primitive in GF(2^{3k}) → u is NOT a 7th power in GF(2^{3k})
#     (iii) u^{2^k−1} is NOT a 7th power in GF(2^{3k})
#     (iv) θ^{2^t−1} IS a 7th power in GF(2^{3k}) when 3∣t
# VBF API used: SBox, differential_uniformity, gf_pow, gf_is_dth_power,
#               subfield_elements, in_subfield

include(joinpath(@__DIR__, "helpers.jl"))


# `v` is given as an ω-exponent, never as an index into `subfield_elements`: that
# list is sorted by integer value, so index 1 is always the element 1 and never a
# power of ω. GF(2^k)* ⊂ GF(2^{3k})* is generated by ω^{(2^{3k}−1)/(2^k−1)}, i.e.
# by ω²¹ for k=2 (n=6) and ω²⁷³ for k=4 (n=12).

const THEOREM3_CASES = [
    # (k, s, label, v_exp) — v_exp is the ω-exponent of v, `nothing` ⇒ v = 0
    # k=2, s=1, n=6: gcd(1,6)=1, 3∤2, 3|(2+1)=3
    (2, 1, "n=6  k=2 s=1  v=0 (binomial, ref. [2])",         nothing),
    (2, 1, "n=6  k=2 s=1  v=ω²¹=59 (trinomial, new)",             21),
    # k=4, s=5, n=12: gcd(5,12)=1, 3∤4, 3|(4+5)=9
    (4, 5, "n=12 k=4 s=5  v=0 (binomial)",                   nothing),
    (4, 5, "n=12 k=4 s=5  v=ω²⁷³=1971 (trinomial)",              273),
]


"""
    theorem3_sbox(k, s, v_exp; modulus) -> SBox

Build a Family 2 SBox with u=2 (primitive in GF(2^{3k})) and `v = ω^{v_exp}`,
where `v_exp === nothing` means `v = 0` (the binomial subfamily). The Theorem 3
hypotheses — including `v ∈ GF(2^k)` — are enforced by `family2_lut`.
"""
function theorem3_sbox(k::Int, s::Int, v_exp::Union{Int,Nothing};
                        modulus::Int = primitive_polynomial(3k))
    n = 3k
    v = v_exp === nothing ? 0 : gf_pow(2, v_exp, n; modulus)
    SBox(family2_lut(k, s, 2, v; modulus))
end


"""
    theorem3_sweep_n6(; modulus) -> (tested, total, all_apn)

Exhaustive sweep of the Theorem 3 parameter space at n=6, (k,s)=(2,1): every
primitive `u ∈ GF(64)` (φ(63) = 36 of them) against every `v ∈ GF(4)` (4), i.e.
all 144 valid (u,v) pairs. Runs in well under a second.
"""
function theorem3_sweep_n6(; modulus::Int = primitive_polynomial(6))
    k, s, n = 2, 1, 6
    us = [u for u = 1:(1 << n) - 1 if is_primitive_element(u, n; modulus)]
    vs = subfield_elements(n, k; modulus)
    total, all_apn = length(us) * length(vs), true
    for u in us, v in vs
        if differential_uniformity(SBox(family2_lut(k, s, u, v; modulus))) != 2
            all_apn = false
        end
    end
    (total, total, all_apn)
end


# Parameter tuples that violate a Theorem 3 hypothesis. The first five isolate a
# single hypothesis; `k ≡ 0 mod 3` cannot be isolated, because `3|k` together with
# `3|(k+s)` forces `3|s` and hence `gcd(s,3k) ≥ 3`.
const THEOREM3_VIOLATIONS = [
    # (k, s, u, v, why)
    (2, 5, 2, 1, "k+s=7 ≢ 0 mod 3"),
    (2, 1, 1, 1, "u=1 is not primitive in GF(64) (order 1)"),
    (2, 1, 6, 1, "u=6 is not primitive in GF(64) (order 9)"),
    (2, 1, 2, 4, "v=4 ∉ GF(4)"),
    (2, 1, 2, 7, "v=7 ∉ GF(4)"),
    (3, 1, 2, 1, "k=3 ≡ 0 mod 3 (and k+s=4 ≢ 0 mod 3)"),
]


"""
    theorem3_nonprimitive_n6(; modulus) -> (apn, total)

Theorem 3 requires `u` primitive, but at n=6 that is *sufficient, not necessary*:
of the 27·4 = 108 pairs with `u ∈ GF(64)*` non-primitive and `v ∈ GF(4)`, 72 are
still APN — exactly those with `ord(u) ∈ {7, 21}`, i.e. `u` a nonzero cube —
while the remaining 36 (`ord(u) ∈ {1, 3, 9}`) are not. Recorded so that
`family2_lut`'s `ArgumentError` is read as enforcing the paper's hypothesis, not
as a claim that non-primitive `u` never works.
"""
function theorem3_nonprimitive_n6(; modulus::Int = primitive_polynomial(6))
    k, s, n = 2, 1, 6
    us = [u for u = 1:(1 << n) - 1 if !is_primitive_element(u, n; modulus)]
    vs = subfield_elements(n, k; modulus)
    apn = count(differential_uniformity(
                    SBox(family2_lut(k, s, u, v; modulus, validate = false))) == 2
                for u in us for v in vs)
    (apn, length(us) * length(vs))
end


"""
    theorem3_necessity_report(io)

Show that the Theorem 3 hypotheses are *necessary*: each tuple in
`THEOREM3_VIOLATIONS` breaks one of them, is rejected by `family2_lut`, and
yields a function that is not APN.
"""
function theorem3_necessity_report(io::IO = stdout)
    println(io, "  Hypotheses are necessary — each tuple below breaks a hypothesis,")
    println(io, "  is rejected by family2_lut, and is not APN:")
    all_rejected = true
    for (k, s, u, v, why) in THEOREM3_VIOLATIONS
        modulus  = primitive_polynomial(3k)
        rejected = false
        try
            family2_lut(k, s, u, v; modulus)
        catch e
            rejected = e isa ArgumentError
        end
        du = differential_uniformity(
            SBox(family2_lut(k, s, u, v; modulus, validate = false)))
        ok = rejected && du != 2
        all_rejected &= ok
        print_check("k=$k s=$s u=$u v=$v: $why → rejected, du = $du ≠ 2", ok, io)
    end
    println(io)
    print_check("All Theorem 3 hypothesis violations rejected and non-APN",
                all_rejected, io)
    apn, total = theorem3_nonprimitive_n6()
    print_kv("u primitive is sufficient, not necessary (n=6)",
             "$apn of $total non-primitive (u,v) pairs are still APN — exactly " *
             "those with ord(u) ∈ {7, 21}", io)
    println(io)
end


function lemma2_report(io::IO = stdout)
    print_section("Lemma 2 — Seventh-power properties in GF(2^{3k}) (Section 3)", io)
    println(io, "  7 | 2^r−1 iff 3 | r.  For k=2, n=6:")
    println(io)

    k, n = 2, 6
    modulus = primitive_polynomial(n)
    sub     = subfield_elements(n, k; modulus)                   # GF(4) ⊂ GF(64)

    # (i) Every θ ∈ GF(2^k) is a 7th power *in GF(2^k)*: since 3∤k=2 we have
    #     7∤(2^k−1)=3, so x ↦ x^7 permutes GF(2^k). This must be evaluated inside
    #     GF(2^k): `gf_is_dth_power(θ, 7, n)` would answer the different (also
    #     true, but unused) question of 7th-power-ness in GF(2^{3k}).
    seventh_powers_of_sub = Set(gf_pow(θ, 7, n; modulus) for θ in sub)
    all_in_k_are_7th = seventh_powers_of_sub == Set(sub)
    print_check("(i)  every θ ∈ GF(4) is θ'^7 for some θ' ∈ GF(4) [7∤(2²−1)=3]",
                all_in_k_are_7th, io)

    # (ii) u=2 primitive in GF(64) is NOT a 7th power [7|(2^6−1)=63]
    u = 2
    print_check("(ii) u=2 primitive in GF(64) is not a 7th power [7|63]",
                !gf_is_dth_power(u, 7, n; modulus), io)

    # (iii) u^{2^k−1} = u^3 is NOT a 7th power in GF(64)
    u3 = gf_pow(u, (1 << k) - 1, n; modulus)
    print_check("(iii) u^{2^k−1}=u^3 is not a 7th power in GF(64)",
                !gf_is_dth_power(u3, 7, n; modulus), io)

    # (iv) θ^{2^t−1} is a 7th power for 3∣t: check t=3 and t=6
    t3 = gf_pow(u, (1 << 3) - 1, n; modulus)   # u^7
    t6 = gf_pow(u, (1 << 6) - 1, n; modulus)   # u^63 = 1
    print_check("(iv) u^{2^3−1}=u^7 is a 7th power in GF(64) [3|3]",
                gf_is_dth_power(t3, 7, n; modulus), io)
    print_check("(iv) u^{2^6−1}=1 is a 7th power in GF(64) [3|6]",
                gf_is_dth_power(t6, 7, n; modulus), io)
    println(io)
end


function theorem3_report(io::IO = stdout)
    lemma2_report(io)

    print_section("Theorem 3 — Family 2 trinomial APN (Section 3)", io)
    println(io, "  F(x) = u·x^{2^{n−k}+2^{k+s}} + u^{2^k}·x^{2^s+1} + v·x^{2^{k+s}+2^s}")
    println(io, "  Conditions: gcd(s,3k)=1, k≢0 mod 3, k+s≡0 mod 3,")
    println(io, "              u primitive in GF(2^{3k}), v ∈ GF(2^k).")
    println(io, "  v=0: binomial from [Budaghyan-Carlet-Felke-Leander 2006].")
    println(io)

    all_pass = true
    for (k, s, label, v_exp) in THEOREM3_CASES
        F   = theorem3_sbox(k, s, v_exp)
        apn = differential_uniformity(F) == 2
        all_pass &= apn
        print_check(label, apn, io)
    end
    println(io)
    print_check("All Theorem 3 instances APN", all_pass, io)
    print_kv("u", "2 = ω (primitive in GF(2^n))", io)
    println(io)

    theorem3_necessity_report(io)

    tested, total, sweep_apn = theorem3_sweep_n6()
    print_check("n=6 (k,s)=(2,1) sweep: $tested/$total valid (u,v) pairs APN",
                sweep_apn, io)
    print_kv("completeness",
             "n=6 (k,s)=(2,1): all $total valid (u,v) pairs (36 primitive u × 4 " *
             "v ∈ GF(4), 100%); n=12 (k,s)=(4,5): 2 instances (u=ω, v ∈ {0, ω²⁷³}) " *
             "out of φ(4095)·16 = 1728·16 = 27 648 (0.007%)", io)
end


if abspath(PROGRAM_FILE) == @__FILE__
    theorem3_report()
end
