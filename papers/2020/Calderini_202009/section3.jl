"""
    admissible_check(F, A1_cols, A2_cols) -> Bool

Direct check that F₁(x) = A₁(x) + A₂∘F(x) is a permutation (the admissibility
of L₁ in Observation 1 / Procedure 2). `A1_cols`, `A2_cols` are the images of
the standard basis under the F₂-linear maps A₁, A₂.
"""
function admissible_check(F::SBox{N,T}, A1_cols::Vector{T}, A2_cols::Vector{T}) where {N,T}
    n_size = 1 << N
    A1 = F2LinearMap{N,T}(A1_cols)
    A2 = F2LinearMap{N,T}(A2_cols)
    F1_lut = T[A1(T(x)) ⊻ A2(F.lut[x + 1]) for x = 0:(n_size - 1)]
    return is_permutation(SBox{N,T}(F1_lut))
end

"""
    observation1_criterion(F, A1_cols, A2_cols) -> Bool

Walsh-side criterion of Observation 1 (eq. 3): F₁ = A₁ + A₂∘F is a permutation
iff W_F(A₁*(λ), A₂*(λ)) = 0 for every λ ≠ 0, with * the adjoint (bit-matrix
transpose in the standard dot-product convention used by `lat`).
"""
function observation1_criterion(
    F::SBox{N,T},
    A1_cols::Vector{T},
    A2_cols::Vector{T},
) where {N,T}
    n_size = 1 << N
    A1t = transpose(F2LinearMap{N,T}(A1_cols))
    A2t = transpose(F2LinearMap{N,T}(A2_cols))
    L = lat(F)
    return all(L[Int(A1t(T(λ))) + 1, Int(A2t(T(λ))) + 1] == 0 for λ = 1:(n_size - 1))
end

"""
    procedure2_admissible_pair(F) -> Union{NamedTuple,Nothing}

Procedure 2, k = 1 fast path: the *first* admissible pair (A₁, A₂) with A₂ ≠ 0,
used by `observation1_demo` and `proposition1_check`. Chooses u ∈ S_F*,
a₁ ∈ ZW(u) and an (n-1)-dim subspace W ⊆ a₁ + ZW(u), then sets A₂*(β₁) = u,
A₂*(βᵢ) = 0 (i ≥ 2), A₁* = [a₁ | basis of W].
Returns `(; A1_cols, A2_cols, u, a1)` or `nothing`.

The complete procedure for every k = dim(U) is `procedure2_pairs`.
"""
function procedure2_admissible_pair(F::SBox{N,T}) where {N,T}
    for u in sf_set(F)
        u == 0 && continue
        zw = zw_set(F, u)
        for a1 in zw
            coset = sort!(unique(UInt32[UInt32(a1 ⊻ v) for v in zw]))
            bases = extract_linear_subspaces(coset, N - 1; max_bits = N)
            isempty(bases) && continue
            W = bases[1]
            A1star = T[T(a1); T.(W)]
            A2star = T[i == 1 ? T(u) : T(0) for i = 1:N]
            A1map = transpose(F2LinearMap{N,T}(A1star))
            A2map = transpose(F2LinearMap{N,T}(A2star))
            A1_cols = T[A1map(T(1) << i) for i = 0:(N - 1)]
            A2_cols = T[A2map(T(1) << i) for i = 0:(N - 1)]
            return (; A1_cols, A2_cols, u, a1)
        end
    end
    return nothing
end

"""
    procedure2_pairs(F) -> Vector{NamedTuple}

Procedure 2 in full (any k = dim U), Section 3: enumerate **all** admissible
linear maps L₁ = (A₁ | A₂), i.e. all L₁ for which F₁(x) = A₁(x) + A₂∘F(x) is a
permutation, in the normal form of Observations 3/4.

For every subspace U ⊆ S_F of dimension k with fixed basis u₁..u_k
(k = 0 gives A₂ = 0, A₁ = id):

- A₂*(βᵢ) = uᵢ for i ≤ k, A₂*(βᵢ) = 0 for i > k;
- a₁ ∈ ZW(u₁), …, a_k ∈ ZW(u_k) with **(P1)**
  Σλᵢaᵢ ∈ ZW(Σλᵢuᵢ) for every non-zero (λ₁..λ_k) ∈ F₂ᵏ;
- a_{k+1}..a_n a basis (**(P2)**) of an (n-k)-dim subspace W with **(P3)**
  W \\ {0} ⊆ ⋂_{λ ∈ F₂ᵏ} (Σλᵢaᵢ + ZW(Σλᵢuᵢ)) (Remark 2; the λ = 0 term is
  ZW(0) = F₂ⁿ*, i.e. vacuous), taking one basis per W (Observation 4);
- A₁*(βᵢ) = aᵢ.

For k = n there is no W to choose and (P2)/(P3) are vacuous. Each returned
pair is admissible by Observation 1 — `procedure2_report` asserts this by
checking `is_permutation(F₁)` for every one of them.

Returns `(; A1_cols, A2_cols, k, U)` entries (`U` = the basis of U).
"""
function procedure2_pairs(F::SBox{N,T}) where {N,T}
    n_size = 1 << N
    S = sf_set(F)
    S_nz = UInt32[UInt32(u) for u in S if u != 0]
    ZW = Dict{Int,Vector{Int}}(u => zw_set(F, u) for u in S)
    ZWset = Dict{Int,Set{Int}}(u => Set(v) for (u, v) in ZW)

    out = NamedTuple[]
    emit!(a::Vector{Int}, W::Vector{UInt32}, u::Vector{Int}, k::Int) = begin
        A1star = T[T.(a); T.(W)]
        A2star = T[i <= k ? T(u[i]) : T(0) for i = 1:N]
        A1m = transpose(F2LinearMap{N,T}(A1star))
        A2m = transpose(F2LinearMap{N,T}(A2star))
        push!(
            out,
            (;
                A1_cols = T[A1m(T(1) << i) for i = 0:(N - 1)],
                A2_cols = T[A2m(T(1) << i) for i = 0:(N - 1)],
                k,
                U = copy(u),
            ),
        )
    end

    # k = 0: U = {0} ⟹ A₂ = 0, A₁ = id (the EA-class of F itself).
    emit!(Int[], UInt32[UInt32(1) << i for i = 0:(N - 1)], Int[], 0)

    for k = 1:N
        for ub in extract_linear_subspaces(S_nz, k; max_bits = N)
            u = Int.(ub)
            # combine(λ) -> (Σλᵢuᵢ, Σλᵢaᵢ) for the current a-tuple
            for tup in Iterators.product((ZW[ui] for ui in u)...)
                a = collect(Int, tup)
                sums = [(0, 0) for _ = 0:((1 << k) - 1)]
                for lam = 0:((1 << k) - 1)
                    us = 0
                    as = 0
                    for i = 1:k
                        if (lam >> (i - 1)) & 1 == 1
                            us ⊻= u[i]
                            as ⊻= a[i]
                        end
                    end
                    sums[lam + 1] = (us, as)
                end
                # (P1)
                all(sums[l + 1][2] in ZWset[sums[l + 1][1]] for l = 1:((1 << k) - 1)) ||
                    continue
                if k == N                      # no a_{k+1}..a_n: (P2)/(P3) vacuous
                    emit!(a, UInt32[], u, k)
                    continue
                end
                # (P3) candidate set (Remark 2)
                cand = UInt32[
                    UInt32(w) for w = 1:(n_size - 1) if
                    all((w ⊻ as) in ZWset[us] for (us, as) in sums)
                ]
                isempty(cand) && continue
                for W in extract_linear_subspaces(cand, N - k; max_bits = N)
                    emit!(a, W, u, k)
                end
            end
        end
    end
    return out
end

"""
    procedure2_f1(F, A1_cols, A2_cols) -> SBox

The permutation F₁(x) = A₁(x) + A₂∘F(x) attached to an admissible L₁.
"""
function procedure2_f1(F::SBox{N,T}, A1_cols::Vector{T}, A2_cols::Vector{T}) where {N,T}
    A1 = F2LinearMap{N,T}(A1_cols)
    A2 = F2LinearMap{N,T}(A2_cols)
    return SBox{N,T}(T[A1(T(x)) ⊻ A2(F.lut[x + 1]) for x = 0:((1 << N) - 1)])
end

"""
    permutation_code(F1) -> NTuple

Canonical form (row-reduced echelon basis) of the code 𝒞_{F₁} of Propositions
2 and 3: the F₂-code generated by the rows of the n × 2ⁿ matrix whose columns
are `(F₁(x))_{x ∈ F₂ⁿ}`. Two permutations generate the *same* code iff they
differ by an invertible linear map on the left (F₁' = L ∘ F₁).

Restricted to n ≤ 6, where a row fits in a `UInt64` (the codes are only used
for the paper's small-dimension Procedure-2 pipeline).
"""
function permutation_code(F1::SBox{N,T}) where {N,T}
    N <= 6 || throw(ArgumentError("permutation_code: needs 2ⁿ ≤ 64 bits, got n = $N"))
    rows = UInt64[
        reduce(⊻, (UInt64((F1.lut[x + 1] >> i) & 1) << x for x = 0:((1 << N) - 1)); init = UInt64(0)) for i = 0:(N - 1)
    ]
    piv = 0
    for b = 63:-1:0                       # Gauss-Jordan over F₂
        r = findfirst(i -> i > piv && (rows[i] >> b) & 1 == 1, 1:N)
        r === nothing && continue
        piv += 1
        rows[piv], rows[r] = rows[r], rows[piv]
        for i = 1:N
            i != piv && ((rows[i] >> b) & 1 == 1) && (rows[i] ⊻= rows[piv])
        end
    end
    return Tuple(sort(rows))
end

"""
    left_linear_factor(F1, F1p) -> Union{F2LinearMap,Nothing}

The unique invertible `L` with `F1p = L ∘ F1` (`F1` a permutation), or
`nothing` if none exists. This is what equality of the codes 𝒞_{F₁} = 𝒞_{F₁'}
gives (Propositions 2 and 3).
"""
function left_linear_factor(F1::SBox{N,T}, F1p::SBox{N,T}) where {N,T}
    inv1 = compositional_inverse(F1)
    cols = T[F1p.lut[inv1.lut[(T(1) << i) + 1] + 1] for i = 0:(N - 1)]
    L = F2LinearMap{N,T}(cols)
    is_invertible(L) || return nothing
    all(L(F1.lut[x + 1]) == F1p.lut[x + 1] for x = 0:((1 << N) - 1)) || return nothing
    return L
end

"""
    propositions_2_3_check(F; io) -> Bool

Propositions 2 and 3 (Section 3) on the admissible maps produced by
`procedure2_pairs`.

**Proposition 3** (used by the paper as *the* Section-5 filter, Remark 3: APN ⟹
𝒩ℒ(F) ≠ 0): if 𝒞_{F₁} = 𝒞_{F₁'} then the graphs 𝓛(G_F) and 𝓛'(G_F) give
EA-equivalent functions. Checked here in the strong form of its proof: for
every pair of admissible L₁, L₁' with the same code we recover the unique
invertible L with F₁' = L∘F₁ and verify **L₁' = L∘L₁** (so in particular
A₂' = L∘A₂), then verify the two graph functions are EA-equivalent.

**Proposition 2** is the same conclusion for a possibly-bent F ("no linear
monomials"), under the extra hypothesis Span(Im(A₂∘F)) = Im(A₂); that
hypothesis is checked for every A₂ appearing in the enumeration.

Because 𝒩ℒ(F) ≠ 0 makes L₁ unique for a given F₁ (proof of Proposition 3),
equal codes force the same A₂ up to L — so grouping the L₁'s by code alone is
sound, which is exactly the filter the paper applies.
"""
function propositions_2_3_check(F::SBox{N,T}; io::IO = stdout) where {N,T}
    ps = procedure2_pairs(F)
    f1s = [procedure2_f1(F, p.A1_cols, p.A2_cols) for p in ps]
    all_perm = all(is_permutation, f1s)
    print_kv(io, "#admissible L₁ from Procedure 2 (all k)", length(ps))
    print_check(io, "Every L₁ from Procedure 2 gives a permutation F₁ (Observation 1)", all_perm)

    nl_ok = nonlinearity(F) != 0
    print_check(io, "Proposition 3 hypothesis: 𝒩ℒ(F) ≠ 0 (Remark 3: APN ⟹ true)", nl_ok)

    # Proposition 2's hypotheses: no linear monomial in F, and
    # Span(Im(A₂∘F)) = Im(A₂) for every A₂ the procedure produces.
    no_lin = _has_no_linear_monomials(F)
    span_ok = all(_span_im_a2_of(F, p.A2_cols) == _im_of(p.A2_cols, N, T) for p in ps)
    print_check(io, "Proposition 2 hypothesis: F has no linear monomials", no_lin)
    print_check(io, "Proposition 2 hypothesis: Span(Im(A₂∘F)) = Im(A₂) for every A₂", span_ok)

    groups = Dict{Any,Vector{Int}}()
    for (i, F1) in enumerate(f1s)
        push!(get!(groups, permutation_code(F1), Int[]), i)
    end
    print_kv(io, "#distinct codes 𝒞_{F₁} (Proposition-3 filter)", length(groups))

    factor_ok = true
    for (_, idxs) in groups
        i = idxs[1]
        for j in idxs[2:end]
            L = left_linear_factor(f1s[i], f1s[j])
            if L === nothing
                factor_ok = false
                break
            end
            # L₁' = L ∘ L₁ (the content of Propositions 2/3)
            factor_ok &= all(L(ps[i].A1_cols[c]) == ps[j].A1_cols[c] for c = 1:N)
            factor_ok &= all(L(ps[i].A2_cols[c]) == ps[j].A2_cols[c] for c = 1:N)
        end
    end
    print_check(io, "Equal codes ⟹ L₁' = L∘L₁ (Propositions 2/3, proof step)", factor_ok)

    # …and the conclusion: the graph functions are EA-equivalent.
    ea_ok = true
    for (_, idxs) in groups
        length(idxs) < 2 && continue
        G = _graph_function(F, ps[idxs[1]])
        for j in idxs[2:min(lastindex(idxs), 4)]   # a sample per group keeps this cheap
            Gj = _graph_function(F, ps[j])
            (G === nothing || Gj === nothing) && continue
            ea_ok &= are_ea_equivalent(G, Gj)
        end
    end
    print_check(io, "Equal codes ⟹ EA-equivalent graph functions (Propositions 2/3)", ea_ok)
    return (;
        n_pairs = length(ps),
        n_codes = length(groups),
        all_perm,
        nl_ok,
        no_lin,
        span_ok,
        factor_ok,
        ea_ok,
        prop3 = all_perm && nl_ok && factor_ok && ea_ok,
        prop2 = all_perm && no_lin && span_ok && factor_ok && ea_ok,
    )
end

"""
    univariate_coefficient(F, j; modulus) -> Integer

Coefficient a_j of x^j in the univariate representation of F over GF(2ⁿ)
(1 ≤ j ≤ 2ⁿ-2): a_j = Σ_{x ≠ 0} F(x)·x^{2ⁿ-1-j} (Lagrange interpolation over
F₂ⁿ, using Σ_{x≠0} x^k = 1 iff (2ⁿ-1) | k).
"""
function univariate_coefficient(
    F::SBox{N,T},
    j::Int;
    modulus::Integer = conway_polynomial(N),
) where {N,T}
    q = 1 << N
    acc = 0
    for x = 1:(q - 1)
        acc ⊻= gf_mul(Int(F.lut[x + 1]), gf_pow(x, q - 1 - j, N; modulus), N; modulus)
    end
    return acc
end

"""
    _has_no_linear_monomials(F; modulus) -> Bool

Proposition 2's hypothesis: the *univariate* polynomial of F over GF(2ⁿ) has no
F₂-linear monomial, i.e. the coefficients of x^{2^i} all vanish. (Note this is
not the same as "no degree-1 term in the multivariate ANF": x³ = x·x² does have
linear ANF terms, since bᵢ·bᵢ = bᵢ, yet its univariate form is the single
monomial x³.)
"""
_has_no_linear_monomials(F::SBox{N,T}; modulus::Integer = conway_polynomial(N)) where {N,T} =
    all(univariate_coefficient(F, 1 << i; modulus) == 0 for i = 0:(N - 1))

_im_of(A2_cols::Vector{T}, N::Int, ::Type{T}) where {T} =
    Set(T[F2LinearMap{N,T}(A2_cols)(T(y)) for y = 0:((1 << N) - 1)])

"Span(Im(A₂∘F)) as a set."
function _span_im_a2_of(F::SBox{N,T}, A2_cols::Vector{T}) where {N,T}
    A2 = F2LinearMap{N,T}(A2_cols)
    img = unique(T[A2(F.lut[x + 1]) for x = 0:((1 << N) - 1)])
    span = Set(T[T(0)])
    for v in img
        for w in collect(span)
            push!(span, w ⊻ v)
        end
    end
    return span
end

"Graph function 𝓛(G_F) for an admissible L₁ (random invertible completion)."
function _graph_function(F::SBox{N,T}, p) where {N,T}
    L = complete_ccz_map(p.A1_cols, p.A2_cols, N)
    return ccz_equivalent_function(F, F2AffineMap(L, UInt32(0)))
end

"""
    procedure2_ea_classes(F; io) -> NamedTuple

The paper's own method, end to end (Section 5's opening paragraph):

1. Procedure 2 for every k → all admissible L₁ (`procedure2_pairs`);
2. Proposition 3 → keep one L₁ per code 𝒞_{F₁} (the paper's filter);
3. build the graph function of each survivor and count EA-classes
   (the paper does this with code equivalence on 𝒞₂; here with the complete
   EA decision `are_ea_equivalent`).

Returns `(; n_pairs, n_codes, n_ea)`. `n_codes` is exactly the Corollary-1
bound (the number of simplex codes in 𝒞(F)), and `n_ea` the exact EA-class
count of the CCZ-class of F.
"""
function procedure2_ea_classes(F::SBox{N,T}; io::IO = stdout) where {N,T}
    ps = procedure2_pairs(F)
    seen = Dict{Any,Int}()
    for (i, p) in enumerate(ps)
        key = permutation_code(procedure2_f1(F, p.A1_cols, p.A2_cols))
        haskey(seen, key) || (seen[key] = i)
    end
    reps = [ps[i] for i in values(seen)]
    classes = SBox{N,T}[]
    for p in reps
        G = _graph_function(F, p)
        G === nothing && continue
        any(are_ea_equivalent(G, H) for H in classes) || push!(classes, G)
    end
    print_kv(io, "#admissible L₁ (Procedure 2, all k)", length(ps))
    print_kv(io, "#codes after the Proposition-3 filter", length(reps))
    print_kv(io, "#EA-classes in the CCZ-class of F", length(classes))
    return (; n_pairs = length(ps), n_codes = length(reps), n_ea = length(classes))
end

"Columns of a uniformly random invertible F₂-linear map on F₂ᴺ (rejection)."
function random_invertible_cols(N::Int, ::Type{T}) where {T}
    n_size = 1 << N
    while true
        cols = T.(rand(0:(n_size - 1), N))
        is_invertible(F2LinearMap{N,T}(cols)) && return cols
    end
end

"""
    complete_ccz_map(A1_cols, A2_cols, N) -> F2LinearMap{2N,UInt32}

Complete the top block L₁ = (A₁ | A₂) to an invertible linear map
𝓛 = [[A₁ A₂]; [A₃ A₄]] on F₂²ⁿ (packed (x << N) | y convention of
`ccz_equivalent_function`), choosing random A₃, A₄ until invertible.
"""
function complete_ccz_map(A1_cols::Vector{T}, A2_cols::Vector{T}, N::Int) where {T}
    n_size = 1 << N
    for _ = 1:1000
        A3 = rand(0:(n_size - 1), N)
        A4 = rand(0:(n_size - 1), N)
        cols = Vector{UInt32}(undef, 2N)
        for i = 1:N
            cols[i] = (UInt32(A2_cols[i]) << N) | UInt32(A4[i])       # y-bit i
            cols[N + i] = (UInt32(A1_cols[i]) << N) | UInt32(A3[i])   # x-bit i
        end
        L = F2LinearMap{2 * N,UInt32}(cols)
        is_invertible(L) && return L
    end
    error("complete_ccz_map: no invertible completion found (rank(A1|A2) < n?)")
end

"""
    observation1_demo(F, io) -> Bool

Observation 1 as a genuine equivalence check. Returns overall success.
"""
function observation1_demo(F::SBox{N,T}, io::IO = stdout) where {N,T}
    n_size = 1 << N
    S = sf_set(F)
    print_kv(io, "|S_F|", length(S))
    print_kv(io, "S_F", S)

    ok = true

    # (a) Procedure 2 pair: admissible with A₂ ≠ 0, both sides must say true.
    pr = procedure2_admissible_pair(F)
    if pr === nothing
        print_check(io, "Procedure 2 (k=1) found an admissible pair", false)
        ok = false
    else
        adm = admissible_check(F, pr.A1_cols, pr.A2_cols)
        crit = observation1_criterion(F, pr.A1_cols, pr.A2_cols)
        print_kv(io, "Procedure 2 pair (u, a1)", (pr.u, pr.a1))
        print_check(io, "Procedure-2 pair: F₁ = A₁ + A₂∘F is a permutation", adm)
        print_check(io, "Procedure-2 pair: Walsh criterion (eq. 3) also true", crit)
        ok &= adm && crit
    end

    # (b) A₂ = 0, A₁ invertible: F₁ = A₁ trivially a permutation; both true.
    A1_cols = random_invertible_cols(N, T)
    A2_cols = zeros(T, N)
    b_adm = admissible_check(F, A1_cols, A2_cols)
    b_crit = observation1_criterion(F, A1_cols, A2_cols)
    print_check(io, "(A₁ invertible, A₂=0): permutation and criterion agree", b_adm && b_crit)
    ok &= b_adm && b_crit

    # (c) random pairs: the two sides must agree (usually both false).
    agree = true
    for _ = 1:20
        rA1 = T.(rand(0:(n_size - 1), N))
        rA2 = T.(rand(0:(n_size - 1), N))
        agree &= admissible_check(F, rA1, rA2) == observation1_criterion(F, rA1, rA2)
    end
    print_check(io, "20 random (A₁,A₂): bijectivity ⟺ Walsh criterion", agree)
    ok &= agree

    return ok
end

"""
    corollary1_upper_bound(F; io) -> Int

Corollary 1: upper bound on #EA-classes in the CCZ-class of F =
number of n-dim subspaces of Z(F) (= number of simplex codes in C(F)).
"""
function corollary1_upper_bound(F::SBox{N,T}; io::IO = stdout) where {N,T}
    Z = walsh_zeroes(F)
    bases = extract_linear_subspaces(Z, N; max_bits = 2N)
    n_subspaces = length(bases)
    print_kv(io, "|Z(F)|", length(Z))
    print_kv(io, "#simplex codes in C(F) (= upper bound on EA-classes)", n_subspaces)
    return n_subspaces
end

"""
    proposition1_check(F; io) -> Bool

Proposition 1, checked with real graph transforms: take an admissible
𝓛 = [[A₁ A₂]; [A₃ A₄]] (Procedure 2 top block, random completion), build
G = 𝓛(G_F); replace the top block by L∘L₁ (random invertible L, same bottom
block) and build G'. Per the proof, G and G' are affine-equivalent (hence
EA-equivalent). Returns the computed boolean.
"""
function proposition1_check(F::SBox{N,T}; io::IO = stdout) where {N,T}
    pr = procedure2_admissible_pair(F)
    if pr === nothing
        print_check(io, "Proposition 1: admissible pair available", false)
        return false
    end
    Lfull = complete_ccz_map(pr.A1_cols, pr.A2_cols, N)
    G = ccz_equivalent_function(F, F2AffineMap(Lfull, UInt32(0)))
    if G === nothing
        print_check(io, "Proposition 1: 𝓛(G_F) is a function graph", false)
        return false
    end

    Lr = F2LinearMap{N,T}(random_invertible_cols(N, T))
    A1p = T[Lr(pr.A1_cols[i]) for i = 1:N]
    A2p = T[Lr(pr.A2_cols[i]) for i = 1:N]
    # Same bottom block: read A3/A4 back out of Lfull's columns.
    cols = UInt32[Lfull(UInt32(1) << (i - 1)) for i = 1:(2N)]
    mask = (UInt32(1) << N) - UInt32(1)
    colsp = Vector{UInt32}(undef, 2N)
    for i = 1:N
        colsp[i] = (UInt32(A2p[i]) << N) | (cols[i] & mask)
        colsp[N + i] = (UInt32(A1p[i]) << N) | (cols[N + i] & mask)
    end
    Lfullp = F2LinearMap{2 * N,UInt32}(colsp)
    if !is_invertible(Lfullp)
        print_check(io, "Proposition 1: diag(L,I)·𝓛 invertible", false)
        return false
    end
    Gp = ccz_equivalent_function(F, F2AffineMap(Lfullp, UInt32(0)))
    if Gp === nothing
        print_check(io, "Proposition 1: 𝓛'(G_F) is a function graph", false)
        return false
    end
    same = are_affine_equivalent(G, Gp)
    print_check(io, "Proposition 1: 𝓛 and diag(L,I)·𝓛 give affine-equivalent functions", same)
    return same
end

