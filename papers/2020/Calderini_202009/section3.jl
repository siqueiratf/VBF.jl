# Implements Section 3: Properties and remarks on CCZ-equivalence.
# Paper: Calderini (2020), "On the EA-classes of known APN functions in small dimensions"
# Section: 3 — Properties and remarks on CCZ-equivalence
#
# Pseudocode:
#   1. Observation 1: F₁ = A₁ + A₂∘F is a permutation iff
#      W_F(A₁*(λ), A₂*(λ)) = 0 for all λ ≠ 0 (eq. 3). Verified as a genuine
#      equivalence: LAT-side criterion vs direct bijectivity check, on
#      Procedure-2 pairs (true case), (invertible, 0) pairs (true case), and
#      random pairs (both sides evaluated, must agree).
#   2. Procedure 2, every k = dim(U) (`procedure2_pairs`): all admissible
#      (A₁, A₂) from ZW/S_F data — A₂*(βᵢ) = uᵢ ∈ U ⊆ S_F, A₁*(βᵢ) = aᵢ ∈ ZW(uᵢ)
#      with (P1), and A₁*(β_j) = a_j a basis of an (n-k)-dim W with (P2),(P3)
#      (Remark 2 / Observation 4 normal form). k = 1 fast path:
#      `procedure2_admissible_pair`.
#   3. Propositions 2 and 3: the code 𝒞_{F₁} generated by (F₁(x))_x. Equal codes
#      ⟹ F₁' = L∘F₁ ⟹ L₁' = L∘L₁ ⟹ (Proposition 1) EA-equivalent graph
#      functions. Proposition 3 (𝒩ℒ(F) ≠ 0, so every APN F by Remark 3) is the
#      filter the paper applies in Section 5; Proposition 2 is the variant for F
#      with no linear monomials under Span(Im(A₂∘F)) = Im(A₂). Both hypotheses
#      and both conclusions are checked on Gold x³.
#   4. `procedure2_ea_classes`: the paper's pipeline end to end — Procedure 2
#      (all k) → Proposition-3 code filter → EA-classes of the graph functions.
#      #codes = the Corollary-1 simplex bound; the EA counts match core
#      `ea_class_orbits` (Gold n=4 → 2, Gold n=5 → 3) and Theorem 7/8 for x¹⁵.
#   5. Corollary 1: #EA-classes ≤ #n-dim Walsh-zero subspaces (simplex codes);
#      exact counts asserted for Gold n=4 (16), Gold n=5 (64), Kasami n=5 (2).
#   6. Proposition 1: L₁' = L∘L₁ gives EA-equivalent (in fact affine-equivalent,
#      per the proof) graph functions — checked with real CCZ graph transforms.
# VBF API used: lat, walsh_zeroes, extract_linear_subspaces, F2LinearMap,
#               ccz_equivalent_function, F2AffineMap, are_affine_equivalent,
#               are_ea_equivalent, anf, nonlinearity, compositional_inverse,
#               is_invertible, is_permutation, load_apn_function

